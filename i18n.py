REVERSE = {translated: source for source, translated in ZH_CN.items()}


def resolve_language(value):
    if value == "auto":
        locale = (os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") or
                  os.environ.get("LANG") or "").lower()
        return "zh_CN" if locale.startswith("zh") else "en"
    return value


def translate(text, language):
    source = REVERSE.get(text, text)
    return ZH_CN.get(source, source) if language == "zh_CN" else source
